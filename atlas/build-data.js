#!/usr/bin/env node
// Generates data/onnx-metadata.js (and the manifest) from the Netron checkout's
// source/onnx-metadata.json.
//
// The atlas is a static, dependency-free page. Browsers refuse `fetch()` on
// `file://` URLs, so the dataset is emitted as a classic script that assigns a
// global. Run this after the upstream metadata changes:
//
//     node build-data.js
//
// Point METADATA at another copy of the file if needed.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = process.env.METADATA
    ? path.resolve(process.env.METADATA)
    : [path.resolve(here, '..', 'source', 'onnx-metadata.json'), path.resolve(here, '..', 'netron', 'source', 'onnx-metadata.json')].find((file) => fs.existsSync(file));
if (!source) {
    throw new Error('Could not find onnx-metadata.json; set METADATA to its path.');
}
const target = path.join(here, 'data');

const entries = JSON.parse(fs.readFileSync(source, 'utf8'));
if (!Array.isArray(entries)) {
    throw new Error(`Expected an array in '${source}'.`);
}

const modules = new Set();
const names = new Set();
const dtypes = new Set();
let examples = 0;
let attributes = 0;
let latest = 0;
for (const entry of entries) {
    modules.add(entry.module);
    names.add(entry.name);
    latest = Math.max(latest, entry.version);
    attributes += (entry.attributes || []).length;
    examples += (entry.examples || []).length;
    for (const constraint of entry.type_constraints || []) {
        for (const dtype of constraint.allowed_type_strs || []) {
            dtypes.add(dtype);
        }
    }
}

const manifest = {
    generated: new Date().toISOString(),
    source: path.relative(here, source).split(path.sep).join('/'),
    records: entries.length,
    operators: names.size,
    modules: modules.size,
    latestOpset: latest,
    attributes,
    examples,
    typeStrings: dtypes.size,
};

fs.mkdirSync(target, { recursive: true });

const payload = [
    '// Generated by build-data.js. Do not edit.',
    `// Source: ${manifest.source} @ ${manifest.records} records.`,
    'globalThis.ONNX_METADATA = ' + JSON.stringify(entries) + ';',
    'globalThis.ONNX_METADATA_MANIFEST = ' + JSON.stringify(manifest) + ';',
    '',
].join('\n');
fs.writeFileSync(path.join(target, 'onnx-metadata.js'), payload);

console.log(`Wrote ${path.join('data', 'onnx-metadata.js')} (${(payload.length / 1048576).toFixed(1)} MB)`);
console.log(`  ${manifest.records} records, ${manifest.operators} operators, ${manifest.modules} modules, opset <= ${manifest.latestOpset}`);
